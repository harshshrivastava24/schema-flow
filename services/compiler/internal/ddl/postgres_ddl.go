// Package ddl generates canonical PostgreSQL DDL migration SQL from an IRDocument.
package ddl

import (
	"fmt"
	"sort"
	"strings"

	"github.com/harsh/backendgen/services/compiler/internal/ir"
)

// GeneratePostgresDDL produces a deterministic migrations/0001_init.sql string
// from a postgres-targeted IR document. Entities are sorted in topological
// dependency order by foreign key references; enum types are emitted first.
func GeneratePostgresDDL(doc *ir.IRDocument) (string, error) {
	if doc.Project.Database != ir.Postgres {
		return "", fmt.Errorf("postgres DDL generator called for database %q", doc.Project.Database)
	}

	var sb strings.Builder

	// Preamble
	sb.WriteString("-- Auto-generated by SchemaFlow Compiler\n")
	sb.WriteString("-- IR Version: 1.0 | Target: postgres\n")
	sb.WriteString("-- This file is deterministic: identical IR produces identical SQL.\n\n")
	sb.WriteString("CREATE EXTENSION IF NOT EXISTS \"pgcrypto\";\n\n")

	// ───── Phase 1: Collect and emit enum types (sorted by entity+field ID) ─────
	type enumDef struct {
		typeName string
		values   []string
	}
	var enums []enumDef

	for _, ent := range doc.Entities {
		for _, fld := range ent.Fields {
			if fld.Type == ir.FieldEnum && len(fld.EnumValues) > 0 {
				typeName := fmt.Sprintf("%s_%s", ent.TableName, fld.Name)
				enums = append(enums, enumDef{typeName: typeName, values: fld.EnumValues})
			}
		}
	}

	// Sort enums by type name for determinism
	sort.Slice(enums, func(i, j int) bool { return enums[i].typeName < enums[j].typeName })

	for _, e := range enums {
		quotedVals := make([]string, len(e.values))
		for i, v := range e.values {
			quotedVals[i] = fmt.Sprintf("'%s'", v)
		}
		sb.WriteString(fmt.Sprintf("CREATE TYPE %s AS ENUM (%s);\n\n", e.typeName, strings.Join(quotedVals, ", ")))
	}

	// ───── Phase 2: Topological sort of entities by FK dependencies ─────
	sorted := topoSortEntities(doc)

	// ───── Phase 3: CREATE TABLE statements ─────
	for _, ent := range sorted {
		writeCreateTable(&sb, doc, ent)
	}

	// ───── Phase 4: Explicit M:N join tables (sorted by relation ID) ─────
	mnRels := make([]ir.Relation, 0)
	for _, rel := range doc.Relations {
		if rel.Kind == ir.ManyToMany {
			mnRels = append(mnRels, rel)
		}
	}
	sort.Slice(mnRels, func(i, j int) bool { return mnRels[i].ID < mnRels[j].ID })

	for _, rel := range mnRels {
		writeJoinTable(&sb, doc, rel)
	}

	// ───── Phase 5: Indexes on foreign keys and unique fields ─────
	for _, ent := range sorted {
		writeIndexes(&sb, doc, ent)
	}

	return sb.String(), nil
}

// writeCreateTable emits a single CREATE TABLE statement for the given entity.
func writeCreateTable(sb *strings.Builder, doc *ir.IRDocument, ent *ir.Entity) {
	sb.WriteString(fmt.Sprintf("CREATE TABLE %s (\n", ent.TableName))

	lines := make([]string, 0, len(ent.Fields))
	var pkName string

	for _, fld := range ent.Fields {
		col := fmt.Sprintf("  \"%s\" %s", fld.Name, pgType(doc, ent, &fld))

		if fld.IsPK() {
			pkName = fld.Name
			col += " PRIMARY KEY"
		}

		if fld.IsRequired() && !fld.IsPK() {
			col += " NOT NULL"
		}

		if fld.IsUnique() && !fld.IsPK() {
			col += " UNIQUE"
		}

		if fld.Default != nil {
			col += fmt.Sprintf(" DEFAULT %s", pgDefault(&fld))
		}

		lines = append(lines, col)
	}

	// If auth is enabled, ensure the auth entity table has password column
	hasPassword := false
	for _, fld := range ent.Fields {
		if fld.Name == "password" {
			hasPassword = true
			break
		}
	}
	if doc.Auth.Enabled && !hasPassword && (strings.EqualFold(ent.Name, "User") || strings.EqualFold(ent.Name, "Account")) {
		lines = append(lines, "  \"password\" TEXT")
	}

	// Add foreign key constraints inline
	for _, rel := range doc.Relations {
		if rel.Kind == ir.ManyToMany {
			continue
		}
		if rel.ToEntityID != ent.ID {
			continue
		}
		if rel.ForeignKeyField == "" {
			continue
		}

		fromEnt := doc.EntityByID(rel.FromEntityID)
		if fromEnt == nil {
			continue
		}
		fromPK := fromEnt.PrimaryKeyField()
		if fromPK == nil {
			continue
		}

		onDelete := "RESTRICT"
		if rel.OnDelete != "" {
			onDelete = strings.ReplaceAll(string(rel.OnDelete), "_", " ")
		}

		fkLine := fmt.Sprintf("  CONSTRAINT fk_%s_%s FOREIGN KEY (\"%s\") REFERENCES %s(\"%s\") ON DELETE %s",
			ent.TableName, rel.ForeignKeyField,
			rel.ForeignKeyField,
			fromEnt.TableName, fromPK.Name,
			onDelete,
		)
		lines = append(lines, fkLine)
	}

	_ = pkName
	sb.WriteString(strings.Join(lines, ",\n"))
	sb.WriteString("\n);\n\n")
}

// writeJoinTable emits a CREATE TABLE for an M:N join relationship.
func writeJoinTable(sb *strings.Builder, doc *ir.IRDocument, rel ir.Relation) {
	fromEnt := doc.EntityByID(rel.FromEntityID)
	toEnt := doc.EntityByID(rel.ToEntityID)
	if fromEnt == nil || toEnt == nil {
		return
	}

	fromPK := fromEnt.PrimaryKeyField()
	toPK := toEnt.PrimaryKeyField()
	if fromPK == nil || toPK == nil {
		return
	}

	// Deterministic join table name: alphabetical order of the two table names
	tables := []string{fromEnt.TableName, toEnt.TableName}
	sort.Strings(tables)
	joinTable := fmt.Sprintf("%s_%s", tables[0], tables[1])

	fromCol := fmt.Sprintf("%s_id", ir.ToLowerSnake(fromEnt.Name))
	toCol := fmt.Sprintf("%s_id", ir.ToLowerSnake(toEnt.Name))

	// If both columns would have the same name (self-relation), disambiguate
	if fromCol == toCol {
		fromCol = fromCol + "_a"
		toCol = toCol + "_b"
	}

	sb.WriteString(fmt.Sprintf("CREATE TABLE %s (\n", joinTable))
	sb.WriteString(fmt.Sprintf("  \"%s\" %s NOT NULL,\n", fromCol, pgTypeForFieldType(fromPK.Type)))
	sb.WriteString(fmt.Sprintf("  \"%s\" %s NOT NULL,\n", toCol, pgTypeForFieldType(toPK.Type)))
	sb.WriteString(fmt.Sprintf("  PRIMARY KEY (\"%s\", \"%s\"),\n", fromCol, toCol))
	sb.WriteString(fmt.Sprintf("  CONSTRAINT fk_%s_%s FOREIGN KEY (\"%s\") REFERENCES %s(\"%s\") ON DELETE CASCADE,\n",
		joinTable, fromCol, fromCol, fromEnt.TableName, fromPK.Name))
	sb.WriteString(fmt.Sprintf("  CONSTRAINT fk_%s_%s FOREIGN KEY (\"%s\") REFERENCES %s(\"%s\") ON DELETE CASCADE\n",
		joinTable, toCol, toCol, toEnt.TableName, toPK.Name))
	sb.WriteString(");\n\n")
}

// writeIndexes emits CREATE INDEX statements for FK fields and non-PK unique fields.
func writeIndexes(sb *strings.Builder, doc *ir.IRDocument, ent *ir.Entity) {
	// Collect FK field names for this entity
	fkFields := make(map[string]bool)
	for _, rel := range doc.Relations {
		if rel.ToEntityID == ent.ID && rel.ForeignKeyField != "" && rel.Kind != ir.ManyToMany {
			fkFields[rel.ForeignKeyField] = true
		}
	}

	type idxDef struct {
		name string
		sql  string
	}
	var indexes []idxDef

	for _, fld := range ent.Fields {
		if fld.IsPK() {
			continue // PK already has implicit index
		}
		if fkFields[fld.Name] {
			idx := fmt.Sprintf("CREATE INDEX idx_%s_%s ON %s (\"%s\");\n",
				ent.TableName, fld.Name, ent.TableName, fld.Name)
			indexes = append(indexes, idxDef{name: fmt.Sprintf("idx_%s_%s", ent.TableName, fld.Name), sql: idx})
		}
	}

	// Sort indexes by name for determinism
	sort.Slice(indexes, func(i, j int) bool { return indexes[i].name < indexes[j].name })
	for _, idx := range indexes {
		sb.WriteString(idx.sql)
	}
	if len(indexes) > 0 {
		sb.WriteString("\n")
	}
}

// pgType maps an IR field to its PostgreSQL column type.
func pgType(doc *ir.IRDocument, ent *ir.Entity, fld *ir.Field) string {
	if fld.Type == ir.FieldEnum {
		return fmt.Sprintf("%s_%s", ent.TableName, fld.Name)
	}
	return pgTypeForFieldType(fld.Type)
}

// pgTypeForFieldType maps an IR FieldType to its PostgreSQL equivalent.
func pgTypeForFieldType(ft ir.FieldType) string {
	switch ft {
	case ir.FieldString:
		return "TEXT"
	case ir.FieldInt:
		return "INTEGER"
	case ir.FieldDecimal:
		return "NUMERIC"
	case ir.FieldBool:
		return "BOOLEAN"
	case ir.FieldTimestamp:
		return "TIMESTAMPTZ"
	case ir.FieldUUID:
		return "UUID"
	case ir.FieldJSON:
		return "JSONB"
	default:
		return "TEXT"
	}
}

// pgDefault maps an IR default value to its PostgreSQL DEFAULT expression.
func pgDefault(fld *ir.Field) string {
	if fld.Default == nil {
		return ""
	}
	switch v := fld.Default.(type) {
	case string:
		switch v {
		case "uuid()":
			return "gen_random_uuid()"
		case "now()":
			return "NOW()"
		default:
			// Enum member or string literal
			return fmt.Sprintf("'%s'", v)
		}
	case bool:
		if v {
			return "TRUE"
		}
		return "FALSE"
	case float64:
		// JSON numbers decode as float64
		if v == float64(int64(v)) {
			return fmt.Sprintf("%d", int64(v))
		}
		return fmt.Sprintf("%g", v)
	default:
		return fmt.Sprintf("'%v'", v)
	}
}

// ───── Topological sort ─────

// topoSortEntities returns entities sorted so that FK targets appear before
// FK sources. Falls back to alphabetical entity ID order for unrelated entities.
func topoSortEntities(doc *ir.IRDocument) []*ir.Entity {
	// Build adjacency: toEntityId depends on fromEntityId (FK points to parent)
	deps := make(map[string][]string)    // entityID -> list of entity IDs it depends on
	entByID := make(map[string]*ir.Entity)

	for i := range doc.Entities {
		entByID[doc.Entities[i].ID] = &doc.Entities[i]
		deps[doc.Entities[i].ID] = nil
	}

	for _, rel := range doc.Relations {
		if rel.Kind == ir.ManyToMany {
			continue
		}
		// toEntity has the FK column → it depends on fromEntity
		if _, ok := entByID[rel.ToEntityID]; ok {
			if _, ok2 := entByID[rel.FromEntityID]; ok2 {
				deps[rel.ToEntityID] = append(deps[rel.ToEntityID], rel.FromEntityID)
			}
		}
	}

	// Kahn's algorithm
	inDegree := make(map[string]int)
	for id := range entByID {
		inDegree[id] = 0
	}
	for _, depList := range deps {
		for _, dep := range depList {
			inDegree[dep] = inDegree[dep] // ensure key exists
		}
	}
	// Count in-degree based on reverse: if A depends on B, B must come first
	// So we reverse: edge B -> A (B must precede A)
	graph := make(map[string][]string) // from -> [to]
	for id, depList := range deps {
		for _, dep := range depList {
			graph[dep] = append(graph[dep], id)
		}
	}
	for id := range entByID {
		inDegree[id] = 0
	}
	for _, targets := range graph {
		for _, t := range targets {
			inDegree[t]++
		}
	}

	// Collect zero in-degree nodes sorted alphabetically for determinism
	var queue []string
	for id := range entByID {
		if inDegree[id] == 0 {
			queue = append(queue, id)
		}
	}
	sort.Strings(queue)

	var result []*ir.Entity
	for len(queue) > 0 {
		node := queue[0]
		queue = queue[1:]
		result = append(result, entByID[node])

		neighbors := graph[node]
		sort.Strings(neighbors)
		for _, n := range neighbors {
			inDegree[n]--
			if inDegree[n] == 0 {
				queue = append(queue, n)
			}
		}
		sort.Strings(queue)
	}

	// If there are cycles, append remaining entities alphabetically
	if len(result) < len(doc.Entities) {
		remaining := make([]string, 0)
		added := make(map[string]bool)
		for _, e := range result {
			added[e.ID] = true
		}
		for id := range entByID {
			if !added[id] {
				remaining = append(remaining, id)
			}
		}
		sort.Strings(remaining)
		for _, id := range remaining {
			result = append(result, entByID[id])
		}
	}

	return result
}
